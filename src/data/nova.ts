/**
 * 「爆灯」——把一大口灯油直接打出去。
 *
 * 这个游戏里"灯油"一直同时是**火力**（`damageScale = 0.65 + 油量 × 0.7`）、
 * **视野**（`lightRadius = 96 + 油量 × 224`）和**弹药**（倾灯倒一瓢要 0.15 桶）。
 * 而燃爆（新手第一个按下去的大招）从最早那版起就是**固定**收 0.16 桶——
 * 不论你的灯是刚满的还是快灭的，它都收一样多、打一样狠。
 * 于是它一直是"冷却到了就按"的东西，玩家手里那盏灯有多满，跟这一发毫无关系。
 *
 * 这一版把它变成**按烧掉的油算账**：
 * 灯火旺过 `overburnAt` 时按燃爆，这一发会**自己烧掉一大口油**（`overburnCost`，是平时的两倍），
 * 换来一圈更大、更狠、还带灼烧的火——这就是「爆灯」。
 *
 * 为什么代价放在油上、而不是再加一个冷却：油是这个游戏里唯一**同时管着看和打**的东西。
 * 烧掉 0.32 桶不只是少一点伤害，是接下来十几秒你**看得见的范围小了一半**
 * （满桶 320px → 烧完 0.23 桶时 147px）。这才是"换"——不是掉血，是把视野押上去。
 *
 * 于是它和这几件事咬在一起：
 * - **倾灯**要 0.72 桶才倒得动、**分灯**一次 0.14：一桶油上有三个动词在抢，
 *   先倾还是先爆，成了每十几秒要做一次的决定；
 * - **夜枭 / 慢灯**那条"越暗越狠"的自伤线，正好是它的反面：
 *   那条线要你把油**压住**，这条线要你把油**打出去**——同一桶油，两种打法；
 * - **掠影**（擦身回油）是它的上弹动作：擦回来的是下一发爆灯。
 */
export const NOVA = {
  /**
   * 平时这一发烧掉多少桶油（v62 之前的固定值，保持不变）。
   * 0.16 是"一盏灯烧十几秒"的量：扣掉它之后灯火还算旺，冷却转回来时正好补得差不多。
   */
  cost: 0.16,
  /**
   * 灯火旺到这个份上，燃爆才会「爆灯」。
   *
   * 为什么是 0.55：倾灯要 0.72 才倒得动，于是 0.55~0.72 这一段是**两个动词真正在抢**的区间——
   * 一盏满灯，你可以先倒一瓢（剩 0.57）再爆，也可以先爆（剩 ≥0.23）再等油回来。
   * 这条线要是压到 0.3 附近，爆灯就变成"随时都能爆"，那种"要不要把这一口攒着"就没有了；
   * 抬到 0.75 又会和倾灯完全重叠，玩家永远只能二选一，看不到"先倒后爆"这种连法。
   */
  overburnAt: 0.55,
  /**
   * 爆灯这一发烧掉多少（平时的两倍）。
   * 和上面的门槛一起构成"烧完还剩多少"：满灯爆完剩 0.68、刚好压线爆完剩 0.23——
   * 前者是"我还能接着打"，后者是"这几秒我得先找油"。同一发招，两种局面。
   */
  overburnCost: 0.32,
  /** 爆灯的伤害倍率（1.2 = 再 +120%，也就是平时的 2.2 倍） */
  overburnDamage: 1.2,
  /** 爆灯的半径加成（0.3 = 半径 ×1.3） */
  overburnArea: 0.3,
  /** 爆灯额外压上去的灼烧层数（和平点那一发自己的层数相加） */
  overburnBurn: 2,
  /** 爆灯那一下的镜头抖动（平时 0.5） */
  overburnShake: 0.95,

  // ── 下面这三条是「爆灯」这条线的遗物在用的钟表（比例写在遗物自己身上）──
  /** 「引线」把烧掉的油烧回来，用这么久摊完 */
  refundSpan: 4,
  /** 「猛火」这一发之后，火还在你身上烧多久 */
  afterglowSpan: 4,
  /** 「炭衣」那层炭裹多久 */
  ashSpan: 3,
} as const;
