/**
 * 「循灯」——收尾阶段最后那几只不再吊着玩家。
 *
 * 这一条是被台架（`tools/bench-waves.mjs`）逼出来的，先有数、才有规则。
 * 读数分两份，第一份是自然局（第一关、6 颗种子、两种走位）：
 * 一波**平均 26 秒，而其中刷怪只占 4.6 秒**——剩下 20.7 秒全在"清场"，
 * 场上只剩 ≤2 只的那段尾巴平均 8.3 秒、最长 62 秒；"350px 内一只怪都没有"的时间
 * 占了整局的 **33.5%**（单波最长 42 秒）。尾巴里点名最多的是**走得最慢的那几只**：
 * 石守 34、喷糜者 40、游尸 52 —— 怪一律刷在玩家 **620~940px** 外，而这几只的脚力是
 * 34~52 px/s，光是走过来就要 12~26 秒；玩家（220px/s）早把身边的清完了，
 * 然后站着等一个还在半路的东西。
 *
 * 第二份是钉死火力之后的 A/B（`--fixed`：同一套武器、不升级，这样两次跑里玩家的火力
 * 一模一样，差出来的只能是这条规则；第一关、6 颗种子、两种走位）：
 *
 *   | 规则 | 清场（守势走位 / 追着打） | 尾巴（≤2 只） | 尾巴 p90 |
 *   | --- | --- | --- | --- |
 *   | 关着 | 14.9 / 13.4 秒 | 6.7 / 4.7 秒 | 19.3 / 10.7 秒 |
 *   | 这一份常数 | 10.8 / 13.2 秒 | **3.1 / 3.3 秒** | **8.1 / 8.2 秒** |
 *
 * 也就是说：**一波的总时长变化不大，变化的是它结束得多干净**——尾巴被砍掉一半以上，
 * 而"挨了多少打"在同一档（关着 150 / 128，开着 152 / 114，在噪声里）。
 *
 * 所以规则只做一件事：**一波已经刷完、场上只剩最后 `aliveAt` 只的时候**，
 * 它们不再"保持距离 / 去扑你的灯台 / 站在那儿当灯塔"，一律直奔你；离得远的还会加速。
 * 为什么只在收尾阶段生效：正在打的那一波里，"喷糜者吊在中距离逼你上前"是它的性格，
 * 不该被抹平；只有在**波次本身已经结束了**的时候，吊着玩家才是纯粹的浪费。
 * 那两只吊在 211px 上、把第 2 波卡了 22 秒的喷糜者，是被这一条里的"保持距离作废"收掉的
 * （尾巴里喷糜者的累计时间：守势 138 秒 → 19.8 秒，追着打 48 秒 → 4.2 秒）。
 *
 * 三条边界（每条都有它守的东西）：
 *   · **`near` 以内一点不改**：`near` 取 300，而灯火最亮时也才照到 320px——
 *     也就是"**你看得见的那几只一点没变**，只有还在暗处没走到的那几只才会加速"。
 *     加速按距离算，走到你面前就自己回到 1 倍（不许变成"隐身加速"）；
 *   · **绝对速度不超过 `ceiling`**：`ceiling` 取玩家**基础**步速（220）的 0.9 倍，
 *     于是"循灯的那几只永远追不上走路（甚至冲刺）的你"是个恒等式——移速升级只会更宽裕。
 *     没有这一条的话，最快的那几只（疾影 132）乘 2.8 就成了 370，比玩家还快，
 *     那就变成"跑不掉"，而不是"不用回头去捡"；
 *   · **首领不吃这一条**：首领有自己那一段（`boss` 阶段），不在收尾窗口里；
 *     而且那么大一块突然加速会显得很假——它的压迫感该来自招式。
 *
 * 同一版里还做了第二件事（「赴灯」，`data/arrival.ts`）：这条规则治的是"**最后几只**还在路上"，
 * 而"**整波怪**怎么到场"是另一个病——慢怪从 620~940px 外出发，光走过来就要 12~27 秒。
 * 那条规则按脚力定生成距离（距离 = 到场时间 × 脚力），把清场阶段的空场又砍掉一半。
 * 两条不重叠：这一条只在**收尾窗口**里生效，那条管的是每一次刷怪本身。
 */
export const HUNT = {
  /** 清场阶段场上只剩这么多只的时候，收尾窗口打开 */
  aliveAt: 4,
  /** 这个距离以内算"已经在跟你打了"：速度与行为都不动（px） */
  near: 300,
  /** 每远这么多像素多给一倍脚力（px） */
  span: 300,
  /** 最多给到这个倍数（再远也还是这个数） */
  mult: 2.8,
  /** 绝对速度上限（px/s）：玩家基础步速 220 的 0.9 倍——"循灯"永远追不上走路的你 */
  ceiling: 198,
} as const;
