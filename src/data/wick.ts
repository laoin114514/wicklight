/**
 * 「拨芯」——第一次把"灯火烧多旺"交到玩家手里。
 *
 * 到这一版为止，灯火一直是一件**自动**的东西：油多就亮、油少就暗（
 * `lightRadius = 96 + 油量 × 224`、`brightness = 0.35 + 油量 × 0.65`），
 * 玩家在它身上能做的只有"多杀点、把油补回来"。也就是说"烧多旺"这件事
 * 从头到尾都由局势决定，不构成一个决定。
 *
 * 可这个游戏的每一句宣传语都在讲同一件事——**灯火既是视野，也是火力**——
 * 那么"要不要把它拨小"本来就该是一个动词：拨小 = 看得近、打得轻，换来的是一桶油能多烧很久。
 *
 * 于是这一版给它加一个开关（`KeyC` / 手机右下角那枚「拨芯」）：灯芯在 0（全开）和 1（拨到底）
 * 之间拧，几个乘数全按它插值。它不改任何一条已有规则，只是让玩家能**自己**把那条曲线往下推。
 *
 * 为什么每一档是这些数：
 * · **省油 ×0.35（少烧 65%）**：这是这个动作存在的理由，它得大到值得按。基础油耗 1.8%/秒，
 *   拨到底 0.63%/秒——**一桶油从 55 秒变成 158 秒**。换算成路：普通移速下"油见底"这件事被推远了三倍。
 * · **视野 ×0.5**：这是它真正的代价，而且是这一版最想卖的那一条。灯火半径满油 320px，
 *   拨到底 160px——**屏幕黑一大半**。危险从"看得见但绕开"变成"看不见，只能听见"，
 *   而这正好是这个游戏最好玩的那种紧张（黑暗不是特效，是信息）。
 * · **火力 ×0.65**：索敌距离跟着灯火走（`findTarget` 只认灯火范围内 +40px），
 *   所以这一条其实**已经**被视野削过一遍了；这里再显式削 35%，是为了让"拨着芯硬打"明确地亏——
 *   不然"在怪堆里拨小、反正近身怪照样打得到"会变成一种零代价的省油刷法。
 * · **亮度 ×0.45**：前三条是规则，这一条是**画面**：火真的变小、光晕真的收进去，
 *   玩家不用看 HUD 也知道自己现在是什么状态。
 * · **速度差（拨小 0.28s / 拨回来 0.42s）**：拨小要**立刻**生效（危险来了先隐下去再说），
 *   拨回来慢一点（重新烧旺本来就要几秒）。和冲刺/燃爆的"按下缓冲"同一个道理：
 *   该快的那一下不能欠着。
 *
 * 和别的东西的关系（都是刻意留下的）：
 * · **倾灯 / 燃爆 / 分灯** 照旧按油算——拨着芯不代表那些动词变便宜，它们花的是"这一桶油里的一块"；
 * · **地里的伏灯、地上的弃灯** 不跟着拨芯变暗：它们是**另外几盏灯**，拨的是你自己这根芯；
 * · **夜枭 / 低油增伤** 那类"越暗越狠"的构筑和它天然合拍（拨芯把油压在低位、又不至于熄灯）；
 * · **灯焰高涨**（掠影）和它正好相反：一个要你把火烧旺，一个要你把它压住——同一根芯，两种走法。
 */
