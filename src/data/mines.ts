/**
 * 「伏灯」——跑着跑着往身后撒一颗雷。
 *
 * 这一局里开火是自动的、瞄准也是自动的，所以**位置**才是玩家真正握着的东西。
 * 到这一版为止，位置只被用来躲（离危险远一点）和擦（掠影，贴着危险走过去）；
 * 伏灯是第三种用法：**事先把它放在那儿**。
 *
 * 于是它的手感和其他十件武器都不一样：别的武器是"打出去就打出去了"，
 * 它是"先埋着，等一个还没发生的事"。等你身后那一串追兵踩上来的时候，
 * 你早就跑到别处去了——这一版想教的就这一件事：位置可以攒，也可以等。
 *
 * 几个数为什么是这些：
 * - `arm`：刚放下就炸的话，它就不是陷阱，而是一颗手感很怪的近身手雷。
 *   留半秒上弦，玩家才有"我把它放在那儿了"的感觉（上弦时脚边会有一圈进度）。
 * - `max`：地上最多六颗。不给上限的话，一路小跑就能在地上铺出一条雷带，
 *   之后画面上所有事都变成"等怪走到我铺好的路上"——那太省事了，也不好看。
 * - `life`：放着不管八秒也自己烧尽。地上不该留下不属于这一场战斗的东西。
 * - `trigger` 由武器数据给（`range`），但判定时**再加一次怪自己的半径**：
 *   大块头（石守）该更早踩响，不然它会擦着雷走过去。
 * - 爆炸不伤玩家：这一局里玩家自己的爆炸从来不伤自己（火球也是），
 *   单独给伏灯开一个例外只会让它在贴脸时变成一件不敢用的武器。
 */
export const MINE = {
  /** 上弦（这期间不会被踩响） */
  arm: 0.55,
  /** 场上同时存在的上限，超出时最老的一颗自己烧尽 */
  max: 6,
  /**
   * 寿命（秒）。这个数是被台架量出来的：跑起来之后，追兵（影蛭 68 速度）离你
   * 每秒钟就远 150px——八秒之后它才走到你八秒前站的地方，而那时候雷早烧尽了。
   * 于是把 8 改成 10。台架上（12 只打不死的影蛭、只带这一件武器、60 秒）：
   * 绕圈跑那种笨走法 8 秒是"踩响 11% / 单件 DPS 29"，10 秒是"13% / 32"，
   * 而"来回拉 / 一直朝一个方向跑"那种会拿自己的雷当路用的走法一动没动（50%+、700~1100 DPS）。
   * 换句话说：它仍然是一把**奖励走位**的武器，只是不再一刀归零。
   */
  life: 10,
  /** 爆炸的击退强度 */
  knockback: 95,
  /** 进化的伏灯炸完留下的那片火 */
  fireLife: 2.6,
  fireDps: 14,
  /** 一次炸到这么多只怪就解锁「伏击」 */
  multiHit: 5,
  /** 雷自己的光：既是为了在黑暗里看得见，也是"它本来就是一盏灯"。
   *  刻意压在主灯之下（半径与强度都比玩家手里的暗一档）：
   *  它是一盏"放着等人来踩"的小灯，不该和随身那盏抢视线。 */
  lightRadius: 74,
  lightIntensity: 0.22,
  /** 灯身那圈小光晕的半径：比"照亮周围"更小一层，标的是"我在这儿" */
  glow: 30,
} as const;
