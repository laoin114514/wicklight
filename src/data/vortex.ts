/**
 * 「旋灯」——扔出去一盏会转的灯，它把周围的东西往里拽。
 *
 * 到这一版为止，"位置"这件事在玩家手里有两个动词：**你**站在哪儿（躲 / 擦 / 掠影），
 * 和**东西**放在哪儿（分灯、伏灯）。旋灯是第三个，而且是反过来的那一个：
 * **你决定它们站在哪儿**。
 *
 * 所以它自己几乎不靠伤害吃饭，它做的是"把手里的东西拢起来"——把一群散开的怪拽到同一点，
 * 再让别的武器去打那一点：燃爆打的是半径、雷弧要跳、光矛要一条线、伏灯要一堆人踩在同一片地上，
 * 全都吃"它们站得有多近"这件事。它是这一局里第一件**给别人打下手**的武器。
 *
 * 几个数为什么是这些：
 * - `life`：拽 1.2 秒。短到不至于把人按在原地，长到足够把一圈人收拢。
 * - `pull`：中心 175px/s，到边缘线性归零。它是**加在怪自己的速度上**的，不是"定住"——
 *   所以疾影（132）挣得出去一点，石守（34）只能被拖着走。这是刻意的：
 *   拽不动的东西才需要玩家换个想法对付。
 * - `bossPull` / `elitePull`：首领几乎拽不动（22%），精英拽一半。首领不该被一件副手武器按在原地，
 *   而且它那么大一块，被拖着走反而显得假。
 * - 收尾那一下**没有击退**（knockback 0）：它是用来拢人的，最后要是把人推开，
 *   等于自己把刚摆好的局面拆了。真正该疼的是下一发。
 * - `burst`：收缩的爆炸半径 = 吸入半径 × 这个数。**刻意比吸入半径小一截**——
 *   因为里头的怪已经被拽到中间了，小圈照样全中；而靠外没被拽动的（疾影、首领、
 *   逆着吸力往外跑的）就掉在圈外。这一条让"拢得多狠"和"炸得多疼"变成同一件事：
 *   吸力没起作用的那一发，收尾也跟着落空。
 *   0.72 是量出来的：1 级吸入半径 116 时收缩圈 83.5，再加怪自己那圈 13 就是 96.5，
 *   离圈边还有将近 20px——站在最外沿的确实躲得掉（测试 `转完缩成一下炸` 钉的就是这个）。
 * - `drag`（进化那一把）：连弹幕一起卷，卷到中心就吞掉。这是那条进化线的题眼——
 *   从"拢怪"变成"替你挡一片"。
 */
export const VORTEX = {
  /** 拽多久（秒） */
  life: 1.2,
  /** 中心的吸力（px/s）；到边缘归零 */
  pull: 175,
  /**
   * 吸力沿半径怎么衰减（`(1 - d/radius) ** pullShape`）。
   *
   * 1 就是线性——最早那版就是线性，台架一量才发现它把"画的圈"和"真的力道"拆开了：
   * 半径 116 的圈里，0.86R 以内的一律被拽到中心，而 0.97R 那圈只挪 19px、0.99R 只剩 5px。
   * 也就是说画出来的那道边界是个**空头承诺**：看着进去了，其实那儿的怪一步都不动。
   * 0.6 次方把外侧垫起来（圈边还剩两成多的力道），于是"站在线里的都会被收走"在内九成的地方成立，
   * 只剩最外沿一道很窄的缝留给"贴着边跑过去"。
   * 注意它不改中心的力道（`pull` 还是 175），所以"175 比石守的 34 快五倍、只有疾影的 132 挣得开"
   * 这套速度上的对抗一个数都没动。
   */
  pullShape: 0.6,
  /** 首领 / 精英的抵抗（1 = 完全拽得动，0 = 完全拽不动） */
  bossPull: 0.22,
  elitePull: 0.6,
  /**
   * 漩涡中心的灯：它本来也是一盏灯，只是这盏是往里照的。
   * 这一盏刻意**比伏灯亮得多**（伏灯 74/0.22，这里 168/0.44）——两个原因：
   * 一是它只在场上待 1.2 秒，亮一下就走，不像伏灯那样长期铺在地上；
   * 二是它得把自己罩住的那一圈**照出来**：被拽进去的怪、往里卷的弹幕、地上那道吸力边界
   * 全都在这盏灯底下才看得见。暗幕是 0.94 的一层，强度不够就等于画了个看不见的东西。
   */
  lightRadius: 168,
  lightIntensity: 0.44,
  /** 旋臂转多快 */
  spin: 3.6,
  /** 收缩那一下的爆炸半径 = 吸入半径 × 这个数 */
  burst: 0.72,
  /** 弹幕被卷到这么近（吸入半径 × 这个数）就算被吞掉 */
  swallow: 0.2,
  /** 一个漩涡里同时拽住这么多只就解「一网打尽」 */
  crowd: 6,
  /**
   * 收尾那一下的伤害**随拢住几只涨**：每多拽住一只 +`reward`。
   *
   * 这一条是给这把武器补上"回报"的：v57 把它做成了纯粹给别人打下手的东西——拢完之后
   * 由燃爆 / 光矛 / 雷弧去打。可那样一来，"拢得多好"这件事在它自己身上看不出任何结果，
   * 玩家也没有理由为了它去挑时机。加上这一条之后，**拢住的那几只正好被拽到中心**，
   * 而中心吃满伤害（`blast` 的边缘衰减是按 `d/radius` 算的），于是"收网"这一步是有账的：
   * 5 只就是 +30，8 只就是 +48。它从"只做铺垫"变成"铺垫做得好，自己也疼一下"。
   */
  reward: 6,
  /**
   * 一次收网**收到**这么多只就解「收网」。
   *
   * 门槛为什么数"只数"、不数"伤害"：最早写的是"收尾打出 120 点以上"，台架一量才发现这个数立不住——
   * 收尾伤害 = 基础 × 灯火系数 + reward × 只数，而基础随等级从 24 涨到 68、灯火系数随油量在
   * 0.65~1.35 之间飘。也就是说**同一个玩家做同一个操作，账能差两倍**：干油的时候，12 只的场面
   * 收尾最多只摸到 116（离 120 差 4 点，怎么打都差一口），满油的时候 6 只就够了。
   * 更糟的是进化那把（基础 166）——满油时空放一下就有 224，等于白送。门槛要是随这两样飘，
   * 它就不是在考操作了。而"这一下打到几只"跟等级、跟油都没关系，只跟"你有没有把它们拢住"有关系，
   * 那才是这一版真正要考的东西。
   *
   * 10 是按收尾圈的大小定的：它只有吸入半径的 0.72 倍（83~109px），
   * 要把 10 只同时摁进这么小一个圈里，得真有一窝东西站在那儿——一波两三只的场合根本解不开。
   * 它刻意比「一网打尽」的 6 只高：那一条数的是**吸力圈**（转的过程中拽住了几只），
   * 这一条数的是**收尾圈**（收的那一下按住了几只）。小圈 + 大数 = 更狠的一档。
   */
  haul: 10,
} as const;
