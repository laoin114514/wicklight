/**
 * 「倾灯」——把灯火本身倒出去。
 *
 * 这一页的数都在讲同一件事：**火是拿你自己的光换来的**。
 *
 * 这个游戏里"灯油"从来不只是根血条：它同时是**火力**（`damageScale = 0.65 + 油量 × 0.7`）、
 * 是**视野**（`lightRadius = 96 + 油量 × 224`，从 96px 到 320px）、也是亮度。
 * 也就是说一个玩家手里其实一直握着"要不要把灯烧旺"这件事，只是以前的武器都不碰它——
 * 你只管捡油，油自己会掉。
 *
 * 倾灯是第一个**花油**的武器（第二个是分灯，一次 0.14 桶）：倒出去的一瓢会变成一片火海，
 * 而它从你的灯里挖走一块——接下来那十几秒你会明显变暗，看得见的东西变少、别的武器也跟着变轻。
 * 于是它把一件原来只能"攒"的资源变成了可以"花"的弹药：
 *
 * - **只在灯火够满时才倒（`minOil`）**：它倒的永远是"最上面那一层"，不会把灯倒空，
 *   所以它不会把玩家推进"油尽"的绝境（那该是失手，不该是武器自己干的）。
 *   这一条同时把射速从"冷却"改成了"你补油有多快"——**冷却不再是它的节奏，油量才是**。
 * - **一瓢多少钱（`cost`）**：0.15 桶（满级 0.10）。红灯区的油一次捡 4% 左右，
 *   擦身一次 0.8%，衰减是每秒 1.8%——所以"倒一瓢"大致等于**四只影蛭的油**，
 *   或者**贴着黑暗擦十秒钟**。它不是白给的，也不是倒不起的。
 * - **火海比爆炸小一圈（`fireSpread`）**：爆炸是打那一下，火是留下来继续烧的。
 *   火比爆炸小一点，是因为"烧一片"要能看见边——两件事同一个半径的话，
 *   玩家分不清自己站在火里还是站在火焰的边沿。
 * - **火里每 `igniteEvery` 秒给怪续一层灼烧**（走的是怪自己那套 burn：每秒 `6 × 层数 × 灼烧加成`）：
 *   同一片火上多倒几瓢，灼烧就会一层层叠上去——**这就是"火上浇油"**。
 * - **自己倒的火不烧自己**：别的火（爆裂菇的词缀、连珠伏灯留在地上的那层火）都烧玩家，
 *   这一层不烧。原因是这一件是**自动开火**的武器：罚一件玩家没有主动按下扳机的东西，
 *   那不叫代价，那叫冤枉。它的代价写在前面的油上。
 *
 * 于是它天然和这几件事咬在一起：**掠影**（擦身回油 = 给它上弹）、
 * **蚀烛**（偷油的怪，一下把它按哑）、**分灯**（同一桶油，两个动词在抢）、
 * 以及「枯灯 / 低语」那类"灯火越低伤害越高"的自伤式构筑（和它正好相反）。
 */
