/**
 * 「燎灯」——把**你自己这盏灯**变成武器的那一件。
 *
 * 到 v62 为止，玩家手里的火全都要"打出去"：枪管在哪儿、往哪儿指，都由索敌决定。
 * 灯火只在一处变成伤害——`damageScale` 那条曲线（灯越亮、打出去的一切越重）。
 * 燎灯是反过来用的那一个：**它没有枪管**。它把"被光罩住"这件事本身当成判定，
 * 每过一小段时间往外烫一遍，罩到谁就烤谁——于是这一件武器的**射程就是你的灯火半径**。
 *
 * 这么设计要付的代价也得说清楚（不然它就是一件"白送的 AoE"）：
 *   · **它够不到灯外**。远程怪吊在你光圈外面放冷枪的时候，燎灯一点忙都帮不上——
 *     这正是这件武器逼你做的那件事：把怪**放进来**，而不是拦在外面。
 *   · **拨了芯它跟着一起小**。拨芯把灯火砍掉一半，罩住的**面积**就只剩四分之一；
 *     再加上 `damageScale` 里那一刀 ×0.65，同一件武器在暗里的输出只剩两成上下。
 *     也就是说「遮光 / 暗火 / 夜步 / 守芯」那四件和它是**对着干**的——这是刻意的：
 *     拨芯这套买的是"摸黑走"，燎灯买的是"亮着烧"，一次开局只该选一边。
 *   · **它不看范围加成**（`面积` / `广照` 那条线）。别的武器靠它变宽，它的宽度写在灯火上——
 *     灯火有自己的四条升级路径（油量、灯火加成、灯焰高涨、拨芯），再叠一层只会两边都说不清。
 *
 * 它是**脉冲**（一下一下），不是每帧持续扣血。两个理由：
 *   1. 每帧扣血在画面上什么都看不见（伤害数字会刷成一片），而脉冲每一下都是一次能看见、
 *      能听见的"烫"——和伏灯 / 旋灯那些"打出去的东西"是同一种反馈；
 *   2. 状态只需要**一个**计时器：不用在每只怪身上挂冷却表（那是一种会跟着怪的数量一起长、
 *      又永远不会有人清的内存）。一盏灯的心跳，本来就只有一个。
 */
export const AURA = {
  /** 一次脉冲同时烫到这么多只，就解「照单全收」。数的是**只数**不是伤害——
   *  伤害要乘灯火（满油 ≈ 1.35 倍、烧干 ≈ 0.65 倍），同一个操作能差两倍，只数才不会飘。 */
  crowd: 8,
  /** 脉冲之后那一点"余温"的时间（秒）：给画面留一拍往外烫的余韵，也用它控制边缘火星的疏密。 */
  pulseFade: 0.22,
  /** 每一次脉冲在光的边缘飞起几粒火星（这是"它在烧"的唯一常驻视觉，不烫到人时也看得见）。 */
  edgeEmbers: 5,
  /** 一次脉冲真的烫到东西时响的音效；空转不响（不然它会变成一挺一直响的机关枪）。 */
  sound: 'aura_pulse',
} as const;
