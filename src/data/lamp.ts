/**
 * 「分灯」——把一小罐灯油点在地上，照亮一圈，把附近的黑暗引过去。
 *
 * 它是这个游戏里**最老的一个动词**（v1 就有），也是到 v82 为止唯一一个
 * "有教学卡、有手机按钮、有代价，却没有任何一件遗物围着它转"的机制：
 * 掠影 / 爆灯 / 拨芯 / 燎灯 / 倾灯 / 伏灯 / 旋灯各有四件，分灯一件都没有。
 * 于是它在玩家手里一直是"偶尔想起来按一下"的东西——不是因为它弱，
 * 而是因为**没有任何一次选择**长在它身上。这一版补的就是这件事。
 *
 * 它为什么值得一套牌：这一局里开火与瞄准都是自动的，位置才是玩家真正握着的东西。
 * 「伏灯」买的是"事先放在那儿"、「旋灯」买的是"当下这一网"，而分灯买的是第三种时间——
 * **把它摆在我打算离开的那个方向**：怪回头走进那盏灯的光里，你往另一边去。
 * 三个位置动词各买一段时间，分灯买的是最短的那一段（几秒），也是最便宜的那一段（一成四的油）。
 *
 * 几个数为什么是这些（改之前先看 `tools/bench-lamp.mjs` 的读数）：
 * - `lure`（引怪半径 340）：这是它全部的用处。量出来的规矩很硬：**灯只管它周围这一圈**——
 *   追兵离灯超过这个半径就重新盯上你。所以"分灯救不了你"的那种时刻，多半不是它没引到人，
 *   而是你把它摆在了"追兵本来就要路过"的那条线上（灯摆在脚下、人往前跑，追兵顺着同一条线
 *   走过来，顺手就把它吃了）。这一条是台架上量出来的，也是这张卡要教玩家的唯一一件事。
 * - `life`（11 秒）：它比冷却（7 秒）长，于是场上可以同时亮着两盏。
 *   一盏灯的寿命不该短于"从你丢下它到你走出它的引怪圈"的时间（10 秒足够走 2000px）。
 * - `cost`（14%）/`minOil`（两成）：分灯是**把油分出去**，油就是光、就是命。
 *   门槛卡在两成，是为了让它永远是"手上的余量分出去一点"，而不是"把自己点死"。
 * - `snuffR`（34px）：凑上来任何一只都能把它吃掉（人越多灭得越快；v107 起墙后的不算），
 *   所以它是"买几秒空间"，不是"清场"——这一条决定了它的上限，也决定了「焚灯」为什么值得存在。
 * - `radius`（152px）比引怪半径小得多：亮着的那一小圈是**它是个光源**的证据，
 *   而外面那一圈很淡的大光才是"这里会引怪"的边界。两条半径都画在同一个位置上，玩家才对得起来。
 */
