/**
 * 「赴灯」——怪从多远的地方刷出来，按它自己的脚力算。
 *
 * 这是「循灯」（见 `data/hunt.ts`）之后的第二次收尾：那一条管的是**一波里最后剩下的几只**，
 * 这一条管的是**整波怪怎么到场**。
 *
 * 台架（`tools/bench-waves.mjs`）把"没事可做"的时间又拆了一层之后，问题就露出来了——
 * 钉死火力的一局里（同一套武器、不升级、跑完四关、两边各 8 颗种子 328 波），
 * 一波 23.0 秒里"350px 内一只怪都没有"的有 8.7 秒，而它分开在两段上：
 * **刷怪阶段 3.2 秒 / 清场阶段 4.4 秒**。刷怪那一小段是"第一批还没走到"，可以理解；
 * 可**清场阶段还有 4.4 秒空场**就说不通了：那个阶段怪已经全刷出来了、场上就是有东西，
 * 只是它们还在半路上。
 *
 * 根因是生成环和脚力从来没对上过：怪一律刷在玩家 **620~940px** 外，走路速度却差 4 倍
 * （石守 34、游尸/砾行者 52、疾影 132 px/s）。于是同一批怪里，最快的 5 秒就到你脸上，
 * 最慢的要走 27 秒——玩家把先到的清完，再站着等慢的那几只把最后一段路走完。
 * 也就是说：**生成环的宽度是给"平均速度"设计的，可玩家感受到的是每一只自己的速度**。
 *
 * 所以要改的不是"刷得更近"（那会把快的也一起拉近，等于偷偷加难度），而是
 * **让每一只的"到场时间"大致相等**：`距离 = 到场时间 × 自己的脚力`。
 * 走得慢的从近处出发、走得快的从远处出发，它们就一起到场。
 * `target`(9 秒) 定节奏、`min`/`max` 是两头的夹子、`jitter` 只负责别让它们排成一个正圆——
 * 每个数各守什么边界，写在文件末尾。
 *
 * 台架 A/B（`npm run bench -- --fixed --god --seeds=8 --stages=4`：同一套武器、不升级、打不死，
 * 两边各 8 颗种子都跑完四关、各 328 波，差出来的只能是这条规则；数字就是台架自己报的那几个）：
 *
 *   | 指标 | 守势走位 关 / 开 | 追着打 关 / 开 |
 *   | --- | --- | --- |
 *   | 一波总时长 | 23.0 → **17.7** 秒 | 21.9 → **16.5** 秒 |
 *   | 其中清场 | 12.6 → **7.3** 秒 | 11.6 → **6.4** 秒 |
 *   | 尾巴（≤2 只） | 3.3 → 2.2 秒 | 3.1 → 1.9 秒 |
 *   | 开波到第一次看见怪 | 3.0 → 2.6 秒 | 3.0 → 2.3 秒 |
 *   | 单波空场 | 8.7 → **5.3** 秒 | 8.0 → **4.7** 秒 |
 *   | └ 刷怪阶段空场 | 3.2 → 2.0 秒 | 3.3 → 2.0 秒 |
 *   | └ **清场阶段空场** | 4.4 → **2.1** 秒 | 3.7 → **1.8** 秒 |
 *   | 整局空场占比 | 37.7% → **30.2%** | 36.6% → **28.3%** |
 *   | 整局挨打 | 1158 → **1020** | 1724 → **1336** |
 *
 * 读法：**"刷怪阶段"那 2 秒空场几乎没动**（那是"第一批还在路上"，本来就该有），
 * 掉下来的是**清场阶段**那一段——4.4 秒砍到 2.1 秒（追着打 3.7 → 1.8），
 * 也就是"怪已经全刷出来了、玩家却没东西可打"的时间少了一半还多。
 * 难度没被顺带改掉：**挨打整局反而更少**（守势 −12%、追着打 −22%）——因为"从远处慢慢走过来"
 * 的那一段，玩家本来就既挨不着也打不着，这一条只是把它换成了交战时间。
 *
 * 自然局（第一关，8 颗种子，同一份台架）也看得到同一个方向：空场占比 25.0% → 20.8%（守势）、
 * 28.3% → 22.7%（追着打），单波空场 5.7 → 4.3 / 6.0 → 4.1 秒。
 *
 * 三道边界（每道都有它守的东西）：
 *   · **"看得见就不许刷"是恒等式，不是权衡**：真正生效的近边界是
 *     `max(min, 灯火的当前半径 + margin)`。`min`(430) 只是地板——它在常规灯火（96~320px）下
 *     就已经把生成环推到视野外了；而叠满加成（灯焰高涨 ×1.3 + 多座灯台余温 + 暗视）把灯火
 *     推到 500 上下的时候，环会跟着往外让，**永远不会有一只怪在你眼前凭空出现**。
 *     代价是这种极端亮度下慢怪的到场时间会回到 16 秒上下——但那本来就是个"看得更远"的构筑，
 *     它不缺预警，缺的是别把时间花在走路上的东西；
 *   · **`max`（940px）就是原来那个环的外沿**：只许把慢怪往里拉，**不许把任何一只推得更远**；
 *   · **精英 / 首领不吃这一条**：它们的登场是给玩家看的（有预告、有大字、有顿帧），
 *     刷在视野边上反而像凭空冒出来。导演只在普通怪那条线上传脚力（`spawnPoint(speed)`）。
 */
export const ARRIVAL = {
  /** 目标到场时间（秒）：`距离 = target × 脚力` */
  target: 9,
  /** 近边界的地板（px）：必须大于灯火**常规**最亮时的视野 320px（见文件头的边界说明） */
  min: 430,
  /** 灯火当前半径之外还要再留这么多（px）才算刷怪点：近边界的实际取值是 `max(min, 半径 + 它)` */
  margin: 40,
  /** 最远就是这个（px）：等于原来那个生成环的外沿，不许把任何一只推得更远 */
  max: 940,
  /** 环宽抖动（±这个比例）：全都落在同一个半径上会显得像一圈"弹出来的" */
  jitter: 0.08,
} as const;
