/**
 * 「壁火」（v110）——冲刺撞墙时沿墙面炸开的那一下。
 *
 * 墙从 v84 起是实心的，v86 又让玩家正面撞上去时收掉这次冲刺。那条规矩证明墙不是透明背景，
 * 但玩家为它付的代价一直只有"这次没冲出去"。壁火把同一个碰撞变成一次有意的交换：
 * 用掉一次冲刺、停在墙边，换一圈只烧墙这一侧的火。
 *
 * 三个数这样定：
 *   · 半径 128 / 伤害 32：和「焚灯」那一下（120 / 34）同一档。它不该比一件专门炸灯的遗物更重；
 *   · 两层灼烧：这是火，不是一次纯伤害脉冲；但只续两层，免得贴墙反复撞把首领直接烧穿；
 *   · 击退 70：把人推离墙面一点，撞完不会继续卡在墙脚。
 *   · 余光 0.7 秒 / 半径 190：撞出来的火不该只有一帧粒子。它短暂照亮墙这一侧，
 *     让玩家看得到自己刚把哪几只拍到了墙上；这不是第二段伤害，只是光。
 *
 * 触发条件不在这里：只有**正面**冲刺撞墙才算，斜着擦过去照旧滑行（见 `Game.update` 里
 * 那条 `got < want * 0.25`）。伤害也不交给 `blast()`：那一族是刻意不看墙的爆出去的一下，
 * 而壁火是"墙面这一侧被撞出来的火"，必须逐只问 `wallBetween`，画面才和规则是同一件事。
 */
export const WALLFIRE = {
  radius: 128,
  damage: 32,
  burn: 2,
  knockback: 70,
  afterglow: 0.7,
  glowRadius: 190,
  crowd: 5,
} as const;
